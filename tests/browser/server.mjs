// Synthetic mock backend for the Galería + standalone Media Library browser tests (from the 1.12.13 retest harness).
// No real data: all 300 items are generated here (hashes v000/p001/c010…).
import http from "node:http"; import fs from "node:fs"; import path from "node:path";
const DIST = process.env.DIST, VERSION = process.env.VERSION || "x", PORT = +process.env.PORT || 18913;
const MED = process.env.MEDIA;   // generated by the test runner (ffmpeg testsrc + one PNG); never real media
const QDELAY = +(process.env.QDELAY || 150);
let items, rev, seq;
function reset(n = 300) {
  items = []; rev = 1; seq = 0;
  for (let i = 0; i < n; i++) {
    const video = i % 5 === 0 || i === 10 || i === 119 || i === 125;
    const it = { hash: (video ? "v" : "p") + String(i).padStart(3, "0"), name: (video ? "vid_" : "img_") + i + (video ? ".webm" : ".png"),
      cols: [], names: [], pool: true, folders: [], tags: [], added: 1e6 - i, kind: video ? "video" : "image", dur: 30 };
    if (i === 10) { it.hash = "c010"; it.name = "clip_10.webm"; it.names = [it.name]; it.virtual = { orig: "v005", broken: false }; }
    items.push(it);
  }
}
reset();
const BAD = new Set((process.env.BAD_HASHES || "").split(",").filter(Boolean));   // served as an mp4v (MPEG-4 Part 2) file the browser can't decode
const sorted = (f) => { let a = items.slice(); if (f && f.kind === "video") a = a.filter((x) => x.kind === "video");
  if (f && Array.isArray(f.kinds) && f.kinds.length) a = a.filter((x) => f.kinds.includes(x.kind));
  const s = (f && f.sort) || "date_desc"; a.sort((x, y) => s === "date_asc" ? x.added - y.added : y.added - x.added); return a; };
const meta = () => ({ rev, total: items.length, collections: [], tags: [], folders: [], kinds: { image: items.filter(x => x.kind === "image").length, video: items.filter(x => x.kind === "video").length } });
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const log = [];
async function api(b) {
  const a = b.action; log.push(a + (a === "index_of" ? ":" + b.hash : ""));
  switch (a) {
    case "list": return { ok: true, ...meta() };
    case "query": { await sleep(QDELAY); const L = sorted(b.f); const o = b.offset || 0, l = b.limit || 120;
      const out = { ok: true, v: VERSION, page: { items: L.slice(o, o + l), offset: o, total: L.length, sections: null, kinds: meta().kinds } };
      if (b.meta) Object.assign(out, meta()); return out; }
    case "index_of": { await sleep(QDELAY); return { ok: true, index: sorted(b.f).findIndex((x) => x.hash === b.hash) }; }
    case "media_url": { const it = items.find((x) => x.hash === b.hash); return { ok: true, url: it && it.kind === "video" ? (BAD.has(b.hash) ? "/media/bad.mp4?h=" : "/media/clip.webm?h=") + b.hash : "/media/img.png?h=" + b.hash }; }
    case "thumbs": return { ok: true, thumbs: Object.fromEntries((b.hashes || []).map((h) => [h, "/media/img.png?t=" + h])), pending: [] };
    case "preview": { const it = items.find((x) => x.hash === b.hash) || {}; return { ok: true, image: { src: "/media/img.png?pv=" + b.hash, hash: b.hash, name: it.name, kind: it.kind, tags: [], collections: [], folders: [], files: [], added: it.added, in_pool: true, url: it.kind === "video" ? "/media/clip.webm?h=" + b.hash : undefined } }; }
    case "open": { const L = sorted(b.f); return { ok: true, meta: meta(), scan: { running: false }, default_collection: "", paused: false, v: VERSION, page: { items: L.slice(0, b.limit || 120), offset: 0, total: L.length, sections: null, kinds: meta().kinds } }; }
    case "playback_get": return { ok: true, pos: null, min_s: 300 };
    case "playback_settings": return { ok: true, min_s: 300 };
    default: return { ok: true };
  }
}
function serveFile(req, res, p, type) {
  const st = fs.statSync(p), range = req.headers.range;
  if (range) { const m = /bytes=(\d*)-(\d*)/.exec(range); const s = +m[1] || 0, e = m[2] ? +m[2] : st.size - 1;
    res.writeHead(206, { "Content-Type": type, "Content-Range": `bytes ${s}-${e}/${st.size}`, "Accept-Ranges": "bytes", "Content-Length": e - s + 1 });
    fs.createReadStream(p, { start: s, end: e }).pipe(res); return; }
  res.writeHead(200, { "Content-Type": type, "Content-Length": st.size, "Accept-Ranges": "bytes" }); fs.createReadStream(p).pipe(res);
}
const TYPES = { ".js": "text/javascript", ".css": "text/css", ".html": "text/html", ".webm": "video/webm", ".png": "image/png", ".mp4": "video/mp4" };
http.createServer(async (req, res) => {
  const u = new URL(req.url, "http://x");
  if (req.method === "POST") {
    let body = ""; for await (const c of req) body += c; const b = body ? JSON.parse(body) : {};
    let out;
    if (u.pathname === "/reflib/api") out = await api(b);
    else if (u.pathname === "/test/reset") { reset(); log.length = 0; out = { ok: true }; }
    else if (u.pathname === "/test/capture") { seq++; const h = "f" + String(seq).padStart(3, "0"); items.push({ hash: h, name: "frame_" + seq + ".png", names: [], cols: [], pool: true, folders: [], tags: [], added: 2e6 + seq, kind: "image" }); rev++; out = { ok: true, hash: h, name: "frame_" + seq + ".png" }; }
    else if (u.pathname === "/test/remove") { items = items.filter((x) => x.hash !== b.hash); rev++; out = { ok: true }; }
    else if (u.pathname === "/test/order") { out = { ok: true, order: sorted(b.f).map((x) => x.hash), log: log.slice() }; }
    else { res.writeHead(404); res.end(); return; }
    res.writeHead(200, { "Content-Type": "application/json" }); res.end(JSON.stringify(out)); return;
  }
  if (u.pathname.startsWith("/media/")) return serveFile(req, res, path.join(MED, path.basename(u.pathname)), TYPES[path.extname(u.pathname)]);
  if (u.pathname === "/reflib/media-library/" && process.env.PLUGIN) {
    const P = process.env.PLUGIN, rd = (f) => { try { return fs.readFileSync(path.join(P, f), "utf8"); } catch { return null; } };
    let js = rd("reference_library.js");
    // same composition as plugin.py build_js (shared rule files read from its tuple, so the two never drift)
    const shared = (/for _shared in \(([^)]*)\)/.exec(rd("plugin.py")) || [, ""])[1].match(/"[^"]+\.js"/g).map((x) => x.slice(1, -1));
    for (const sh of shared) { const t = rd(sh); if (t != null) js = t + "\n" + js; }
    for (const ex of ["review_rules.js", "reflib_similarity.js", "reflib_faces.js", "reflib_dupes.js"]) { const t = rd(ex); if (t != null) js += "\n" + t; }
    const css = rd("reference_library.css");
    js = js.split("__REFLIB_SETTINGS__").join(JSON.stringify({ language: "es" })).split("__REFLIB_CSS__").join(JSON.stringify(css)).split("__REFLIB_VERSION__").join(VERSION);
    const html = `<!doctype html><html lang="es"><head><meta charset="utf-8"/><style>${css}</style></head><body><script>window.__REFLIB_STANDALONE__=true;window.__REFLIB_VERSION__=${JSON.stringify(VERSION)};</script><script>${js.replace(/<\/script/g, "<\\/script")}</script></body></html>`;
    res.writeHead(200, { "Content-Type": "text/html; charset=utf-8" }); res.end(html); return; }
  if (u.pathname.startsWith("/reflib/gallery/")) { let p = path.join(DIST, u.pathname.slice("/reflib/gallery/".length) || "index.html");
    if (!fs.existsSync(p) || fs.statSync(p).isDirectory()) p = path.join(DIST, "index.html");
    return serveFile(req, res, p, TYPES[path.extname(p)] || "application/octet-stream"); }
  res.writeHead(404); res.end();
}).listen(PORT, "127.0.0.1", () => console.log("mock on", PORT, DIST, VERSION));
